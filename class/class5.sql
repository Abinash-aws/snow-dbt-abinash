SELECT EMPLOYEE_ID,
       FIRST_NAME,
       SALARY,
       ROW_NUMBER() OVER(ORDER BY SALARY DESC ) AS RID,
       RANK()  OVER(ORDER BY SALARY DESC) AS RNK, 
       DENSE_RANK()  OVER(ORDER BY SALARY DESC) AS DRNK,
       LEAD(SALARY)  OVER(ORDER BY SALARY DESC) AS NEXT_VALUE ,
       LAG(SALARY) OVER(ORDER BY SALARY DESC) AS PREVIOUS_VALUE,
        FROM HR.TCS.EMPLOYEES ;



