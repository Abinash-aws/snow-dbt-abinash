SELECT MID,
       MONTH_NAME,
       AMOUNT,
       LAG(AMOUNT) OVER (ORDER BY MID) AS PREVIOUS_MONTH,
       
       AMOUNT - LAG(AMOUNT) OVER (ORDER BY MID) AS DIFFERENCE,

       CASE
           WHEN AMOUNT > LAG(AMOUNT) OVER (ORDER BY MID)
               THEN 'PROFIT'
           WHEN AMOUNT < LAG(AMOUNT) OVER (ORDER BY MID)
               THEN 'LOSS'
           ELSE 'NO CHANGE'
       END AS PROFIT_OR_LOSS
FROM MONTHLY_SALES
ORDER BY MID;





