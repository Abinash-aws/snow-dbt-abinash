-- CTE  -- COMMON TABLE EXPRATIONS -- IT WILL ACT AS LIKE TEMP TABLE/SESSION TABLES 


WITH CTE_EMP AS 
 (SELECT EMPLOYEE_ID,
       FIRST_NAME,
       SALARY,
       DENSE_RANK() OVER (ORDER BY SALARY DESC) AS DRNK
       FROM HR.TCS.EMPLOYEES )
SELECT * FROM CTE_EMP 
  WHERE DRNK = 5 ;


WITH CTE_EMPS AS 
(SELECT EMPLOYEE_ID,
       FIRST_NAME,
       SALARY,
       DENSE_RANK() OVER (ORDER BY SALARY DESC) AS DRNK
       FROM HR.TCS.EMPLOYEES )
    SELECT * FROM CTE_EMPS 
       WHERE DRNK = 20 ;


-- 2ND WAYS TO FIND  THE EXPRATION (QUALIFY SPECIALLY FOR SNOWFLAKE) 

SELECT EMPLOYEE_ID,
       FIRST_NAME,
       SALARY,
       DENSE_RANK() OVER (ORDER BY SALARY DESC) AS DRNK
       FROM HR.TCS.EMPLOYEES
       QUALIFY DRNK =  6 ;

--DEPARTMENTWISE 2ND HIGHEST SALARY  


SELECT EMPLOYEE_ID,
       FIRST_NAME,
       DEPARTMENT_ID,
       SALARY,
       DENSE_RANK() OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS DRNK
       FROM HR.TCS.EMPLOYEES ;


WITH ECT_EMP AS (
  SELECT EMPLOYEE_ID,
       FIRST_NAME,
       DEPARTMENT_ID,
       SALARY,
       DENSE_RANK() OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS DRNK
       FROM HR.TCS.EMPLOYEES 
)
    SELECT * FROM ECT_EMP WHERE DRNK = 2 ;



--SET OPERATOR  
-- UNION WILL REMOVE THE DUPLIDATES  

SELECT FIRST_NAME  FROM  HR.TCS.EMPLOYEES
  UNION 
SELECT FIRST_NAME FROM HR.TCS.DEPENDENTS ; 


-- UNION ALL IT WILL NOT REMOVE THE DUPICATE 

SELECT FIRST_NAME  FROM  HR.TCS.EMPLOYEES
  UNION ALL
SELECT FIRST_NAME FROM HR.TCS.DEPENDENTS ; 


-- INTERSECT IT WILL FATCH ONLY THE MATCHED VALUES FROM THE RESULTS 

SELECT FIRST_NAME  FROM HR.TCS.EMPLOYEES 
  INTERSECT
SELECT FIRST_NAME FROM HR.TCS.DEPENDENTS ;


-- MINUS THE DATA  SHOULD BE PRESENT IN  ONLY A TABLE NOT IN B TABLE  

SELECT FIRST_NAME  FROM HR.TCS.EMPLOYEES 
  MINUS
SELECT FIRST_NAME FROM HR.TCS.DEPENDENTS ;






